function buildCatalogGift(name, type) {
  const meta = catalogTypeMeta[type];
  const interests = meta.interests.slice();
  const inferredInterestStrength = {};
  catalogInterestRules.forEach(function (rule) {
    if (rule[0].test(name)) {
      interests.push.apply(interests, rule[1]);
      rule[1].forEach(function (interest) {
        inferredInterestStrength[interest] = Math.max(inferredInterestStrength[interest] || 0, rule[2] || 2);
      });
    }
  });

  const types = [type];
  if (/фото|персонал|проекц|местом встречи|радужки|слепок|лицом получателя|внутренними шутками|карикатур/i.test(name)) types.push("Персонализированный");
  if (/свеч|вяз|самодел|оригами|макраме|слепок|штамп|горшок-органайзер/i.test(name)) types.push("Ручная работа");
  if (/кофе|чай|глинтвейн|kinder|сладост|рамен|матча|шоколад/i.test(name)) types.push("Съедобный");
  if (/органайзер|гардероб|стеллаж|вешалка|корзина|дозатор|термокруж|повербанк|флешка|ирригатор|увлажнитель|чехол|держател|абонемент/i.test(name)) types.push("Полезный");
  if (/футболк|худи|носки|фартук/i.test(name)) types.push("Одежда и аксессуары");

  let format = ["Физический подарок"];
  if (type === "Впечатления") format = ["Впечатление"];
  if (type === "Сертификаты и подписки") {
    format = /подписка|донат/i.test(name) ? ["Подписка"] : ["Сертификат"];
  }

  const item = gift(name, {
    recipient: meta.recipients.slice(),
    age: meta.ages.slice(),
    occasion: meta.occasions.slice(),
    interest: uniqueValues(interests),
    format: format,
    type: uniqueValues(types)
  }, { interestStrength: 1, recipientStrength: 1, source: "catalog" });

  Object.entries(inferredInterestStrength).forEach(function (entry) {
    item.interestAffinity[entry[0]] = Math.max(item.interestAffinity[entry[0]] || 0, entry[1]);
  });

  return item;
}

Object.entries(catalogGroups).forEach(function (entry) {
  const type = entry[0];
  entry[1].forEach(function (name) {
    if (!gifts.some(function (item) { return item.name === name; })) {
      gifts.push(buildCatalogGift(name, type));
    }
  });
});

