function gift(name, tags, options) {
  const settings = options || {};
  tags.gender = Array.isArray(tags.gender) && tags.gender.length
    ? uniqueValues(tags.gender)
    : inferGenderTags(tags);
  const defaultInterestStrength = settings.interestStrength || 3;
  const defaultRecipientStrength = settings.recipientStrength || 3;
  const interestAffinity = {};
  const recipientAffinity = {};

  (tags.interest || []).forEach(function (interest) {
    interestAffinity[interest] = defaultInterestStrength;
  });
  (tags.recipient || []).forEach(function (recipient) {
    recipientAffinity[recipient] = defaultRecipientStrength;
  });

  return {
    name: name,
    tags: tags,
    interestAffinity: interestAffinity,
    recipientAffinity: recipientAffinity,
    source: settings.source || "curated",
    adultOnly: Boolean(settings.adultOnly)
  };
}

