function intersectValues(itemValues, selectedValues) {
  return selectedValues.filter(function (value) {
    return itemValues.includes(value);
  });
}

function getRecipientMatch(item, selectedRecipients) {
  const itemRecipients = item.tags.recipient;
  const exact = intersectValues(itemRecipients, selectedRecipients);
  if (exact.length) {
    const exactStrength = exact.reduce(function (best, recipient) {
      return Math.max(best, item.recipientAffinity[recipient] || 1);
    }, 0);
    return { level: exactStrength, values: exact };
  }

  const compatible = selectedRecipients.filter(function (recipient) {
    return (recipientCompatibility[recipient] || []).some(function (fallback) {
      return itemRecipients.includes(fallback);
    });
  });
  return { level: compatible.length ? 1 : 0, values: compatible };
}

function getInterestMatch(item, selectedInterests) {
  const values = intersectValues(item.tags.interest, selectedInterests).filter(function (interest) {
    return (item.interestAffinity[interest] || 1) >= 2;
  });
  const strengths = values.map(function (interest) {
    return item.interestAffinity[interest] || 1;
  });
  return {
    values: values,
    maxStrength: strengths.length ? Math.max.apply(null, strengths) : 0,
    totalStrength: strengths.reduce(function (sum, strength) { return sum + strength; }, 0)
  };
}

function getGenderMatch(item, selectedGenders) {
  const values = intersectValues(item.tags.gender || [], selectedGenders);
  return {
    values: values,
    strength: values.length ? ((item.tags.gender || []).length === 1 ? 2 : 1) : 0
  };
}

