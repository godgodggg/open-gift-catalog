function addInterestGift(name, interest, type) {
  const existing = gifts.find(function (item) {
    return item.name.toLocaleLowerCase("ru") === name.toLocaleLowerCase("ru");
  });
  if (existing) {
    existing.tags.interest = uniqueValues(existing.tags.interest.concat(interest));
    existing.interestAffinity[interest] = 3;
    existing.source = "interest-library";
    return;
  }
  const item = buildCatalogGift(name, type);
  item.tags.interest = uniqueValues(item.tags.interest.concat(interest));
  item.interestAffinity[interest] = 3;
  item.source = "interest-library";

  if (interest === "Курение") {
    item.tags.recipient = ["Мужу", "Папе", "Другу / подруге", "Брату / сестре"];
    item.tags.age = ["Молодому человеку (18–25 лет)", "Взрослому (26–35 лет)", "Человеку среднего возраста (36–50 лет)", "Пожилому человеку (от 51 года)"];
    item.recipientAffinity = {};
    item.tags.recipient.forEach(function (recipient) {
      item.recipientAffinity[recipient] = 3;
    });
  }

  gifts.push(item);
}

