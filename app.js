function answerSummary(values) {
  if (!values || !values.length) return "";
  if (values.includes(ANY_OPTION)) return ANY_OPTION;
  return values.length === 1 ? values[0] : values.length + " выбрано";
}

function renderProgress() {
  routeCounter.textContent = "Шаг " + Math.min(state.currentStep + 1, steps.length) + " из " + steps.length;
  progress.innerHTML = steps.map(function (step, index) {
    const saved = state.answers[step.key];
    const current = index === state.currentStep;
    const shown = current && state.draft.size ? Array.from(state.draft) : saved;
    const complete = Array.isArray(saved) && !current;
    const status = current ? "is-current" : complete ? "is-complete" : "";
    const returnIcon = complete ? '<span class="progress__return" aria-hidden="true">↙</span>' : "";
    const label = '<span class="progress__label">' + (index + 1) + ". " + step.label + "</span>";
    const value = '<span class="progress__value">' + answerSummary(shown) + "</span>";
    const enabled = complete ? 'aria-label="Вернуться к шагу: ' + step.label + '"' : "disabled";
    return '<li class="progress__item ' + status + '"><button class="progress__step" type="button" data-route-step="' + index + '" ' + enabled + ">" + label + value + returnIcon + "</button></li>";
  }).join("");

  progress.querySelectorAll("[data-route-step]:not(:disabled)").forEach(function (button) {
    button.addEventListener("click", function () {
      goToStep(Number(button.dataset.routeStep));
    });
  });
}

function renderOptions() {
  const step = steps[state.currentStep];
  options.innerHTML = step.options.map(function (option, index) {
    const selected = state.draft.has(option);
    const classes = "option " + (option === ANY_OPTION ? "option--any " : "") + (selected ? "is-selected" : "");
    const eyebrow = option === ANY_OPTION ? '<span class="option__index">НЕ УЧИТЫВАТЬ</span>' : "";
    return '<button class="' + classes + '" type="button" data-value="' + option + '" aria-pressed="' + selected + '">' + eyebrow + '<span class="option__name">' + option + "</span></button>";
  }).join("");

  options.querySelectorAll("[data-value]").forEach(function (button) {
    button.addEventListener("click", function () {
      toggleOption(button.dataset.value);
    });
  });
  updateActions();
}

function updateActions() {
  const count = state.draft.has(ANY_OPTION) ? 0 : state.draft.size;
  nextButton.disabled = state.draft.size === 0;
  nextButton.textContent = state.currentStep === steps.length - 1 ? "Показать идеи →" : "Далее →";
  selectionCount.textContent = state.draft.has(ANY_OPTION)
    ? "Категория не будет учитываться"
    : count
      ? "Выбрано: " + count
      : "Выберите хотя бы один вариант";
}

function toggleOption(value) {
  if (value === ANY_OPTION) {
    state.draft = state.draft.has(ANY_OPTION) ? new Set() : new Set([ANY_OPTION]);
  } else {
    state.draft.delete(ANY_OPTION);
    state.draft.has(value) ? state.draft.delete(value) : state.draft.add(value);
  }
  renderOptions();
  renderProgress();
}

function animatePanel() {
  panel.classList.remove("is-changing");
  requestAnimationFrame(function () {
    panel.classList.add("is-changing");
  });
}

function renderQuestion() {
  const step = steps[state.currentStep];
  actions.hidden = false;
  question.textContent = step.question;
  hint.textContent = step.hint;
  renderOptions();
  renderProgress();
  animatePanel();
}

function advanceStep() {
  if (!state.draft.size) return;
  const step = steps[state.currentStep];
  state.answers[step.key] = Array.from(state.draft);

  if (state.currentStep === steps.length - 1) {
    renderResults();
    return;
  }

  state.currentStep += 1;
  state.draft = new Set(state.answers[steps[state.currentStep].key] || []);
  renderQuestion();
  scrollToSelector();
}

function goToStep(index) {
  steps.slice(index + 1).forEach(function (step) {
    delete state.answers[step.key];
  });
  state.currentStep = index;
  state.draft = new Set(state.answers[steps[index].key] || []);
  renderQuestion();
  scrollToSelector();
}

function scrollToSelector() {
  questionScroll.scrollTo({ top: 0, behavior: "smooth" });
}

function getActiveFilters() {
  const active = {};
  Object.entries(state.answers).forEach(function (entry) {
    const values = entry[1].filter(function (value) {
      return value !== ANY_OPTION;
    });
    if (values.length) active[entry[0]] = values;
  });
  return active;
}

function rankGifts() {
  const filters = getActiveFilters();
  const hasInterestFilter = Array.isArray(filters.interest) && filters.interest.length > 0;
  return gifts.map(function (item, index) {
    const matches = [];
    const interestMatches = [];
    Object.entries(filters).forEach(function (entry) {
      const key = entry[0];
      entry[1].forEach(function (value) {
        if ((item.tags[key] || []).includes(value)) {
          matches.push(value);
          if (key === "interest") interestMatches.push(value);
        }
      });
    });
    return {
      item: item,
      score: matches.length,
      interestScore: interestMatches.length,
      matches: matches,
      index: index
    };
  }).sort(function (a, b) {
    if (hasInterestFilter && b.interestScore !== a.interestScore) {
      return b.interestScore - a.interestScore;
    }
    return b.score - a.score || a.index - b.index;
  });
}

function renderResults() {
  state.currentStep = steps.length;
  state.draft = new Set();
  const ranked = rankGifts();
  const activeCount = Object.values(getActiveFilters()).reduce(function (sum, values) {
    return sum + values.length;
  }, 0);
  const hasInterestFilter = Boolean(getActiveFilters().interest && getActiveFilters().interest.length);

  question.textContent = "ИДЕИ ПО ВАШЕМУ МАРШРУТУ";
  hint.textContent = hasInterestFilter
    ? "Сначала показаны подарки по выбранным интересам, затем — остальные по числу совпадений."
    : activeCount
      ? "Сначала показаны подарки с наибольшим количеством совпадений."
    : "Фильтры не выбраны — идеи показаны в исходном порядке.";
  actions.hidden = true;

  const cards = ranked.map(function (result) {
    const matchText = result.matches.length ? result.matches.join(" · ") : "Нет точных совпадений";
    const scoreText = hasInterestFilter
      ? result.interestScore + " по интересу · " + result.score + " всего"
      : result.score + " совп.";
    return '<article class="gift-card"><div class="gift-card__top"><span class="gift-card__score">' + scoreText + "</span></div><h3>" + result.item.name + '</h3><p class="gift-card__matches">' + matchText + "</p></article>";
  }).join("");

  const sortLabel = hasInterestFilter ? "ИНТЕРЕС → СОВПАДЕНИЯ ↓" : "ПО СОВПАДЕНИЯМ ↓";
  options.innerHTML = '<div class="results-summary"><span>НАЙДЕНО ИДЕЙ: ' + ranked.length + '</span><span>СОРТИРОВКА: ' + sortLabel + '</span></div><div class="results-grid">' + cards + "</div>";
  renderProgress();
  animatePanel();
  scrollToSelector();
}

