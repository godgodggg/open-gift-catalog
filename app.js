const genderOptions = ["Женщина", "Мужчина"];

function inferGenderTags(tags) {
  const recipients = tags.recipient || [];
  const femaleRecipients = ["Девушке", "Девочке", "Жене", "Маме", "Дочери", "Лучшей подруге", "Бабушке"];
  const maleRecipients = ["Парню", "Мальчику", "Мужу", "Папе", "Сыну", "Лучшему другу", "Дедушке"];
  const hasFemaleRecipient = recipients.some(function (recipient) {
    return femaleRecipients.includes(recipient);
  });
  const hasMaleRecipient = recipients.some(function (recipient) {
    return maleRecipients.includes(recipient);
  });

  if (hasFemaleRecipient && !hasMaleRecipient) return ["Женщина"];
  if (hasMaleRecipient && !hasFemaleRecipient) return ["Мужчина"];
  return genderOptions.slice();
}

